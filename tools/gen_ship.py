#!/usr/bin/env python3
"""Generate include/ship_data.h: the shaded player ship, pre-rendered at 32 headings as masked 16x16 four-plane
sprites (planes 0-3 and a coverage word per row, bit 15 = leftmost pixel).

The ship is a handful of flat-shaded facets (lit left wing, shaded right wing, canopy, nose and wing-tip
accents) that are rotated and squashed by the game's 0.9 x 0.7333 world-to-screen scale, then sampled 3x3 per pixel
so the edges look smooth. Colours are palette indices (see set_palette in src/platform_atari_st.c).

Usage: python tools/gen_ship.py [include/ship_data.h] [--preview ship.ppm]
"""
import math
import sys

HEADINGS = 32
SIZE = 16
SX, SY = 0.9, 176.0 / 240.0   # world -> screen scale of the playing field

# (colour, polygon in the ship's own frame: x forward, y to the right). The first facet that covers a sample wins.
FACETS = [
    (6, [(3.6, 0.0), (0.2, -1.6), (0.2, 1.6)]),                        # canopy
    (2, [(8.2, 0.0), (5.4, -0.9), (5.4, 0.9)]),                        # nose highlight
    (7, [(-8.0, -5.6), (-5.2, -3.7), (-8.0, -2.8)]),                   # wing tip, left
    (7, [(-8.0, 5.6), (-5.2, 3.7), (-8.0, 2.8)]),                      # wing tip, right
    (12, [(8.0, 0.0), (-8.0, -5.6), (-4.5, 0.0)]),                     # lit wing
    (8, [(8.0, 0.0), (-4.5, 0.0), (-8.0, 5.6)]),                       # shaded wing
    (9, [(-4.5, -0.9), (-6.4, -0.9), (-6.4, 0.9), (-4.5, 0.9)]),       # engine block
]


def inside(poly, x, y):
    sign = 0
    n = len(poly)
    for i in range(n):
        x0, y0 = poly[i]
        x1, y1 = poly[(i + 1) % n]
        cross = (x1 - x0) * (y - y0) - (y1 - y0) * (x - x0)
        if cross != 0:
            s = 1 if cross > 0 else -1
            if sign == 0:
                sign = s
            elif s != sign:
                return False
    return True


def render(heading):
    theta = heading * 2 * math.pi / HEADINGS
    c, s = math.cos(theta), math.sin(theta)
    rows = []
    pixels = []
    for py in range(SIZE):
        line = []
        for px in range(SIZE):
            votes = {}
            for sy in range(3):
                for sx in range(3):
                    dx = (px + (sx + 0.5) / 3 - SIZE / 2) / SX
                    dy = (py + (sy + 0.5) / 3 - SIZE / 2) / SY
                    lx = dx * c + dy * s          # inverse rotation
                    ly = -dx * s + dy * c
                    for colour, poly in FACETS:
                        if inside(poly, lx, ly):
                            votes[colour] = votes.get(colour, 0) + 1
                            break
            total = sum(votes.values())
            if total >= 4:
                line.append(max(votes, key=lambda k: (votes[k], k)))
            else:
                line.append(0)
        pixels.append(line)
        words = [0] * 5
        for px, colour in enumerate(line):
            if colour:
                bit = 0x8000 >> px
                words[4] |= bit
                for plane in range(4):
                    if colour >> plane & 1:
                        words[plane] |= bit
        rows.append(words)
    return rows, pixels


def main():
    out = "include/ship_data.h"
    preview = None
    args = sys.argv[1:]
    if "--preview" in args:
        preview = args[args.index("--preview") + 1]
        del args[args.index("--preview"):args.index("--preview") + 2]
    if args:
        out = args[0]
    sprites = [render(h) for h in range(HEADINGS)]
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_ship.py - do not edit. */\n#ifndef SHIP_DATA_H\n#define SHIP_DATA_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("/* 32 headings x 16 rows x {plane 0, plane 1, plane 2, plane 3, coverage} */\n")
        f.write("static const uint16_t ship_planar[%d][%d][5] = {\n" % (HEADINGS, SIZE))
        for rows, _ in sprites:
            f.write("    {\n")
            for words in rows:
                f.write("        {" + ", ".join("0x%04x" % w for w in words) + "},\n")
            f.write("    },\n")
        f.write("};\n\n#endif\n")
    if preview:
        pal = {0: (10, 10, 40), 2: (255, 255, 255), 6: (255, 255, 0), 7: (255, 40, 40), 8: (60, 80, 220),
               9: (150, 150, 150), 12: (0, 160, 255)}
        scale = 6
        cols = 8
        w = cols * SIZE * scale
        h = (HEADINGS // cols) * SIZE * scale
        img = [[(10, 10, 40)] * w for _ in range(h)]
        for i, (_, pix) in enumerate(sprites):
            ox = (i % cols) * SIZE * scale
            oy = (i // cols) * SIZE * scale
            for y in range(SIZE):
                for x in range(SIZE):
                    for yy in range(scale):
                        for xx in range(scale):
                            img[oy + y * scale + yy][ox + x * scale + xx] = pal[pix[y][x]]
        with open(preview, "w") as f:
            f.write("P3\n%d %d\n255\n" % (w, h))
            for row in img:
                f.write(" ".join("%d %d %d" % p for p in row) + "\n")


if __name__ == "__main__":
    main()
